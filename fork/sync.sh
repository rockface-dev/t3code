#!/usr/bin/env bash
# Rebuilds the fork branch from scratch: upstream's latest commit, then one commit with the
# fork-owned files (fork/) taken from the current tip, then one commit per patch in
# fork/patches (fork/patches.sh), then one generated commit from `node fork/apply.ts`. Nothing is ever rebased, so upstream changes cannot conflict; an upstream
# rename that fork/apply.ts depends on fails the run instead.
#
# Usage: fork/sync.sh [--force]   (run from a clean checkout of the fork branch)
# Leaves the rebuilt branch checked out and does not push. On failure the branch is put back on
# its previous tip. Prints "up-to-date" and exits 0 when neither upstream nor the overlay changed
# since the last sync, unless --force.
set -euo pipefail

upstream_url="${UPSTREAM_URL:-https://github.com/pingdotgg/t3code.git}"
upstream_ref="${UPSTREAM_REF:-main}"
force=false
[[ "${1:-}" == "--force" ]] && force=true

cd "$(git rev-parse --show-toplevel)"
if [[ -n "$(git status --porcelain)" ]]; then
  echo "fork/sync.sh: the working tree has changes; commit or stash them first." >&2
  exit 1
fi

branch="$(git branch --show-current)"
previous_tip="$(git rev-parse HEAD)"
overlay_tree="$(git rev-parse "HEAD:fork")"

git fetch --quiet --no-tags "$upstream_url" "$upstream_ref"
upstream_sha="$(git rev-parse FETCH_HEAD)"

trailer() { git log -1 --format="%(trailers:key=$1,valueonly)" "$previous_tip" | head -1; }
if [[ "$force" == false && "$(trailer Upstream-Commit)" == "$upstream_sha" && "$(trailer Overlay-Tree)" == "$overlay_tree" ]]; then
  echo "up-to-date"
  exit 0
fi

restore() {
  echo "fork/sync.sh: failed; ${branch} is back on ${previous_tip}." >&2
  git reset --quiet --hard
  git checkout --quiet -B "$branch" "$previous_tip"
}
trap restore ERR

git checkout --quiet -B "$branch" "$upstream_sha"
# Checkout only adds files, so anything upstream ever puts under fork/ is removed first; fork/ is
# exactly the previous tip's.
git rm -r --quiet --ignore-unmatch -- fork
git checkout "$previous_tip" -- fork
# --no-verify: upstream's pre-commit hook (vp staged) runs knip against node_modules that may predate
# the new upstream tree. The rebuilt branch is verified afterwards with `vp run check:changed`.
git commit --quiet --no-verify -m "fork: overlay files" -m "Fork-owned files carried from ${previous_tip}."

# Our code changes (fork/patches, BACKLOG M2): one commit each, applied strictly; one that no
# longer applies stops the sync here ("fork/patches.sh: patch <name> no longer applies").
# Nothing happens while fork/patches/.patches doesn't exist.
bash fork/patches.sh apply

node fork/apply.ts
# Swapped values change line lengths; reformat what apply.ts touched so upstream's checks pass.
# A plain assignment, not process substitution, so a git failure reaches the ERR trap.
touched_list="$(git diff --name-only --diff-filter=M)"
touched=()
[[ -z "$touched_list" ]] || mapfile -t touched <<< "$touched_list"
if command -v vp > /dev/null; then
  [[ ${#touched[@]} -eq 0 ]] || vp fmt --no-error-on-unmatched-pattern "${touched[@]}" > /dev/null
else
  echo "fork/sync.sh: vp is not on PATH; skipping formatting." >&2
fi
git add -A
git commit --quiet --no-verify --allow-empty -m "fork: apply fork/identity.json (generated)" \
  -m "Generated by fork/apply.ts. Do not edit; change fork/identity.json or fork/apply.ts." \
  --trailer "Upstream-Commit: ${upstream_sha}" \
  --trailer "Overlay-Tree: ${overlay_tree}"
trap - ERR

echo "rebuilt ${branch} on upstream ${upstream_sha}"

# Upstream's workflows never run here, but their CI and release steps are worth copying into
# fork-*.yml when they change.
# Overlay edits are committed on top of the generated commit, so find the newest generated commit
# (the only kind with an Overlay-Tree trailer). Reporting must never fail the sync.
previous_upstream="$(git log -n 1 --grep='^Overlay-Tree: ' --format='%(trailers:key=Upstream-Commit,valueonly)' "$previous_tip" | head -1 || true)"
if [[ -n "$previous_upstream" && "$previous_upstream" != "$upstream_sha" ]] && git cat-file -e "${previous_upstream}^{commit}" 2> /dev/null; then
  changed="$(git diff --stat=100 "$previous_upstream" "$upstream_sha" -- .github/workflows .github/actions 2> /dev/null)" ||
    changed="(could not compare ${previous_upstream:0:10} with ${upstream_sha:0:10}; check upstream workflow changes by hand)"
  if [[ -n "$changed" ]]; then
    echo "upstream workflow changes since ${previous_upstream:0:10}:"
    echo "$changed"
  fi
fi
